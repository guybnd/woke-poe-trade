# Makes main/src/woke/stash-tabs-data.ts: the Delirium, Delve, Essence and Blight
# stash tabs, from one 2560x1440 screenshot of each with the mouse off the tab.
#
#   python testing/tools/make-stash-tabs.py <delirium.png> <delve.png> <essence.png> <blight.png> [montage folder]
#
# Each tab has a fixed picture that holds no items, which finds it on screen, and a
# fixed set of slots. Names come from icon matching, so check them by eye: with a
# montage folder it writes each slot beside the icon it matched. Icons download from
# poecdn into a folder under the system temp folder.
import base64, json, os, sys, tempfile, urllib.request
import cv2
import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../..'))
MIN_SCORE = 0.25


def grid(xs, ys):
    return [(x, y) for y in ys for x in xs]


ESSENCE_ROW = [257 + round(65.5 * k) for k in range(12)]
ESSENCE_LEFT = [59 + round(65.5 * k) for k in range(7)]
ESSENCE_RIGHT = [572 + round(65.5 * k) for k in range(4)]
FOSSIL_XS = [53 + round(88.7 * k) for k in range(9)]
OIL_ROW_1 = ['Clear', 'Sepia', 'Amber', 'Verdant', 'Teal', 'Azure', 'Indigo']
OIL_ROW_2 = ['Violet', 'Crimson', 'Black', 'Opalescent', 'Silver', 'Golden']

TABS = [
    {
        'family': 'delirium',
        'match': lambda n: n.endswith(' Delirium Orb'),
        'anchor': (272, 358, 98, 36),
        'size': 66,
        'slots': grid([76, 167], [354]) + grid([657, 748], [354]) +
                 grid([76, 167, 259], [446, 538, 631]) +
                 grid([657, 748], [446, 538]) + [(567, 631), (748, 631)]
    },
    {
        'family': 'fossils',
        'match': lambda n: n.endswith(' Fossil'),
        'anchor': (75, 295, 60, 65),
        'size': 72,
        'slots': grid(FOSSIL_XS[1:8], [289]) + grid(FOSSIL_XS, [377]) +
                 grid([97, 185, 318, 407, 495, 629, 717], [466]) + grid([142, 673], [554])
    },
    {
        'family': 'essences',
        'match': lambda n: 'Essence of ' in n,
        'anchor': (470, 560, 150, 220),
        'size': 62,
        'slots': grid(ESSENCE_LEFT, ESSENCE_ROW[:4]) + grid(ESSENCE_LEFT[:6], ESSENCE_ROW[4:8]) +
                 grid(ESSENCE_LEFT[:5], ESSENCE_ROW[8:]) + grid(ESSENCE_RIGHT, ESSENCE_ROW[:4]) +
                 grid(ESSENCE_RIGHT[1:], ESSENCE_ROW[4:8]) + grid(ESSENCE_RIGHT[2:], ESSENCE_ROW[8:])
    },
    {
        'family': 'oils',
        'match': lambda n: n.endswith(' Oil'),
        'anchor': (345, 662, 200, 46),
        'size': 58,
        # The tier order is known, so these need no icon matching.
        'named': {**{(65 + round(82.7 * k), 265): f'{n} Oil' for k, n in enumerate(OIL_ROW_1)},
                  **{(107 + round(82.7 * k), 338): f'{n} Oil' for k, n in enumerate(OIL_ROW_2)}}
    }
]


def fetch(path, url):
    if not os.path.exists(path):
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
        data = urllib.request.urlopen(req, timeout=20).read()
        with open(path, 'wb') as f:
            f.write(data)


def load_icons(items, match):
    cache = os.path.join(tempfile.gettempdir(), 'woke-scarab-icons')
    os.makedirs(cache, exist_ok=True)
    icons = {}
    for item in items:
        name, url = item.get('refName'), item.get('icon')
        if not name or not url or not match(name):
            continue
        path = os.path.join(cache, base64.urlsafe_b64encode(name.encode()).decode() + '.png')
        fetch(path, url)
        icon = cv2.imread(path, cv2.IMREAD_UNCHANGED)
        if icon is not None and icon.ndim == 3 and icon.shape[2] == 4:
            icons[name] = icon
    return icons


def score(im, x, y, size, icon):
    # Not the top left, as the stack count covers it. Icons sit a little inside the slot.
    pad = 10
    crop = im[y - pad:y + size + pad, x - pad:x + size + pad]
    best = -1
    for s in range(size - 8, size + 9, 2):
        small = cv2.resize(icon, (s, s), interpolation=cv2.INTER_AREA)
        alpha = small[:, :, 3].copy()
        alpha[:s // 3, :s // 2] = 0
        r = cv2.matchTemplate(crop, small[:, :, :3], cv2.TM_CCOEFF_NORMED, mask=cv2.merge([alpha] * 3))
        r[~np.isfinite(r)] = -1
        best = max(best, float(r.max()))
    return best


def main(args):
    shots = args[:len(TABS)]
    montage = args[len(TABS)] if len(args) > len(TABS) else None
    with open(os.path.join(ROOT, 'renderer/public/data/en/items.ndjson'), encoding='utf8') as f:
        items = [json.loads(line) for line in f]
    flat = lambda a: ','.join(str(int(v)) for v in a.flatten())
    out = ['// Generated by testing/tools/make-stash-tabs.py from 2560x1440 screenshots.',
           '// Pixels are at 1440p, the only size these tabs are read at. Offsets are from the top left of `anchor`,',
           '// a picture of the tab that holds no items.',
           '',
           'export interface StashTabData {',
           '  family: string',
           '  anchor: { x: number, y: number, width: number, height: number, gray: number[] }',
           '  size: number',
           '  slots: Array<{ name: string, dx: number, dy: number }>',
           '}',
           '',
           'export const STASH_TABS: StashTabData[] = [']
    for tab, shot in zip(TABS, shots):
        im = cv2.imdecode(np.fromfile(shot, np.uint8), cv2.IMREAD_COLOR)
        icons = load_icons(items, tab['match'])
        size = tab['size']
        if 'named' in tab:
            named = {s: (n, 1.0) for s, n in tab['named'].items()}
        else:
            table = sorted(((score(im, x, y, size, ic), n, (x, y)) for (x, y) in tab['slots'] for n, ic in icons.items()), reverse=True)
            named, taken = {}, set()
            for sc, n, s in table:
                if sc >= MIN_SCORE and s not in named and n not in taken:
                    named[s] = (n, sc)
                    taken.add(n)
            print(tab['family'], 'icons', len(icons), 'slots', len(tab['slots']), 'named', len(named),
                  'unnamed', [s for s in tab['slots'] if s not in named], 'unused', sorted(set(icons) - taken)[:12])
        ax, ay, aw, ah = tab['anchor']
        gray = im.astype(np.float32).mean(axis=2)
        out.append('  {')
        out.append(f"    family: '{tab['family']}',")
        out.append(f'    anchor: {{ x: {ax}, y: {ay}, width: {aw}, height: {ah}, gray: [{flat(gray[ay:ay + ah, ax:ax + aw])}] }},')
        out.append(f'    size: {size},')
        out.append('    slots: [')
        for s, (n, sc) in sorted(named.items(), key=lambda kv: (kv[0][1], kv[0][0])):
            q = f'"{n}"' if "'" in n else f"'{n}'"
            out.append(f'      {{ name: {q}, dx: {s[0] - ax}, dy: {s[1] - ay} }},')
        out[-1] = out[-1].rstrip(',')
        out.append('    ]')
        out.append('  },')
        if montage:
            cells = []
            for s, (n, sc) in sorted(named.items(), key=lambda kv: (kv[0][1], kv[0][0])):
                x, y = s
                cell = np.zeros((130, 180, 3), np.uint8)
                c = im[y:y + size, x:x + size]
                cell[:90, :90] = cv2.resize(c, (90, 90), interpolation=cv2.INTER_NEAREST)
                ic = cv2.resize(icons[n], (90, 90), interpolation=cv2.INTER_AREA)
                a = ic[:, :, 3:] / 255.0
                cell[:90, 90:180] = (ic[:, :, :3] * a).astype(np.uint8)
                words = n.replace(' Delirium Orb', '').replace(' Fossil', '').replace(' Oil', '').replace('Essence of ', '')
                cv2.putText(cell, words[:24], (2, 106), cv2.FONT_HERSHEY_SIMPLEX, .4, (255, 255, 255), 1)
                cv2.putText(cell, f'{sc:.2f}', (2, 124), cv2.FONT_HERSHEY_SIMPLEX, .4, (0, 255, 255), 1)
                cells.append(cell)
            while len(cells) % 10:
                cells.append(np.zeros((130, 180, 3), np.uint8))
            sheet = np.vstack([np.hstack(cells[i:i + 10]) for i in range(0, len(cells), 10)])
            cv2.imencode('.png', sheet)[1].tofile(os.path.join(montage, tab['family'] + '.png'))
    out[-1] = '  }'
    out.append(']')
    with open(os.path.join(ROOT, 'main/src/woke/stash-tabs-data.ts'), 'w', encoding='utf8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(sys.argv[1:])
