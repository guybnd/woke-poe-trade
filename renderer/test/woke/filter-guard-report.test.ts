// Writes docs/loot-filter-guard.md: what the loot filter guard protects, in
// plain words, from the same checks the guard tests make. The file is a
// snapshot: if a change alters what's protected, this test fails until the
// report is refreshed with `npx vitest run test/woke/filter-guard-report -u`
// (in renderer/), so the change shows up in review.
import { describe, it, expect } from 'vitest'
import {
  FILTERS, PRECIOUS, SETUPS, blockLook, compose, dropLook, isNeverSinkBlock, isRedBeam,
  harshName, pairSetups, presets, source, hostilePrices
} from '../helpers/filter-guard'
import type { Look } from '../helpers/filter-guard'

const SHORT: Record<string, string> = {
  '0-SOFT': 'Soft',
  '1-REGULAR': 'Regular',
  '2-SEMI-STRICT': 'Semi-strict',
  '3-STRICT': 'Strict',
  '4-VERY-STRICT': 'Very strict',
  '5-UBER-STRICT': 'Uber',
  '6-UBER-PLUS-STRICT': 'Uber+',
  'VAAL-3-STRICT (style)': 'Vaal style'
}

const mark = (l: Look) => l.shown && l.sound && l.beam && l.icon ? '✓' : [l.shown ? 'shows' : 'HIDDEN', l.sound ? '' : 'silent', l.beam ? '' : 'no beam'].filter(Boolean).join(', ')

function changesFor (name: string): string {
  const s = SETUPS.find(x => x.name === name)!
  const doc = compose(FILTERS.find(f => f.name === '1-REGULAR')!.text, s).doc
  const out: string[] = []
  for (const p of PRECIOUS) {
    const before = dropLook(source('1-REGULAR'), p.facts)
    const after = dropLook(doc, p.facts)
    const lost = [before.sound && !after.sound ? 'sound' : '', before.beam && !after.beam ? 'beam' : '', before.icon && !after.icon ? 'map icon' : ''].filter(Boolean)
    if (lost.length) out.push(`${p.name}: ${lost.join(' and ')} off`)
  }
  const before = source('1-REGULAR').blocks
  const theirs = doc.blocks.filter(isNeverSinkBlock)
  const red = before.map((b, i) => [b, theirs[i]] as const).filter(([b]) => isRedBeam(b))
  const quiet = red.filter(([b, a]) => blockLook(b).sound && !blockLook(a).sound).length
  const dark = red.filter(([b, a]) => blockLook(b).beam && !blockLook(a).beam).length
  if (quiet) out.push(`${quiet} red-beam rules silenced`)
  if (dark) out.push(`${dark} red-beam rules lose their beam`)
  return out.length ? out.join('; ') : 'nothing'
}

function report (): string {
  const L: string[] = []
  L.push('# Loot filter guard: what is protected')
  L.push('')
  L.push('Generated by `renderer/test/woke/filter-guard-report.test.ts` from the same checks the guard tests make. Don\'t edit by hand.')
  L.push('')
  L.push('## The promise')
  L.push('')
  L.push('Whatever presets you switch on, NeverSink\'s most valuable drops still **show**, still **make their sound**, and still get their **beam and map icon**, and their label never gets smaller. A preset may only take away what it says it does:')
  L.push('')
  L.push('- **Quiet mode** takes the sound of rules NeverSink ranks below your line (it keeps tiers 1 to N).')
  L.push('- **Beams only for top tiers** takes the beam and map icon of rules ranked below your line.')
  L.push('- Nothing else may hide, silence or un-beam them.')
  L.push('')
  L.push(`Checked on NeverSink ${source('1-REGULAR').version}, every strictness (${FILTERS.filter(f => !/style/.test(f.name)).map(f => SHORT[f.name]).join(', ')}) and one style (Vaal), through the same code that writes your filter. Prices are as hostile as they get: everything not listed below is priced at 0.01c, so the price presets hide as much as they can. (The dust preset gets a fixed list of bases, as the disenchant prices would give it.)`)
  L.push('')
  L.push('## The drops')
  L.push('')
  L.push(`| Drop | Why | NeverSink's rule | ${FILTERS.map(f => SHORT[f.name]).join(' | ')} |`)
  L.push(`|---|---|---|${FILTERS.map(() => ':-:').join('|')}|`)
  for (const p of PRECIOUS) {
    L.push(`| ${p.name} | ${p.why} | \`${p.rule}\` | ${FILTERS.map(f => mark(dropLook(source(f.name), p.facts))).join(' | ')} |`)
  }
  L.push('')
  L.push('✓ = shows, sound, beam and map icon in NeverSink as it comes; HIDDEN = NeverSink itself hides it there. The guard checks each one keeps that under every setup below.')
  L.push('')
  L.push('Besides these, every rule NeverSink gives a **red beam** (its top two looks: the white-background apex tier and the tier below) keeps its own sound, beam and map icon under every setup, rule by rule (whether an added rule above catches its drops first is checked through the drops listed above):')
  L.push('')
  L.push('| File | Red-beam rules |')
  L.push('|---|--:|')
  for (const f of FILTERS) L.push(`| ${SHORT[f.name]} | ${source(f.name).blocks.filter(isRedBeam).length} |`)
  L.push('')
  L.push('## Setups tried')
  L.push('')
  L.push('Each one on every file. "Taken away" is what the preset is allowed to take, as it happened on Regular; anything else would fail the guard.')
  L.push('')
  L.push('| Setup | Taken away |')
  L.push('|---|---|')
  for (const s of SETUPS) L.push(`| ${s.name} | ${changesFor(s.name)} |`)
  L.push('')
  L.push(`Also: all ${pairSetups().length} pairs of presets at their harshest (on Regular and Uber+), and ${25 * FILTERS.length} seeded random mixes of presets and settings, 25 per file, with the safety net on in about half (\`filter-guard-pairs\` and \`filter-guard-random\` tests).`)
  L.push('')
  L.push('## Also checked')
  L.push('')
  L.push('- With nothing switched on, the saved file is NeverSink\'s, byte for byte.')
  L.push('- Every setup\'s file passes the game\'s load check, and with every preset on it writes and reads back the same.')
  L.push('- NeverSink\'s rules are never removed or reordered; the presets only add rules and change actions.')
  L.push('- With no prices, or only thin (unreliable) prices, the cheap currency, card, unique and splinter presets hide nothing.')
  L.push('- If you hide NeverSink\'s top currency tier yourself, Divines go (your call), and the safety net brings them back with a sound and beam, even with every preset at its harshest.')
  L.push('')
  L.push('## Open (not settled)')
  L.push('')
  const sacred = changesFor(harshName('quiet'))
  L.push(`- **Quiet mode and beams at 1 tier** take NeverSink's second tier too, which wears a red beam. On Regular: ${sacred}. The default (2 tiers) keeps them. Should the lowest setting be 2?`)
  const crash = compose(FILTERS[1].text, { name: 'crash', netOn: true, presets: presets({ cheapCurrency: { on: true, chaos: 1 } }) }, hostilePrices({ 'Divine Orb': 0.5 })).doc
  L.push(`- **A wrong price can hide a top drop.** The price presets trust poe.ninja: if Divine Orb were listed at 0.5c, "hide currency under 1c" would hide it (${dropLook(crash, PRECIOUS[1].facts).shown ? 'shown' : 'hidden'} in this check, safety net on too, since the net reads the same prices). The same goes for cards and uniques. A guard could skip anything NeverSink gives a red beam. Pinned as a known gap in \`filter-guard.test.ts\`.`)
  L.push('- **Item tier from a real drop.** The tiered gear check gives the drop its item tier by hand: the copied item text doesn\'t show it yet (WOKEPOET-153), so the in-game preview can\'t judge those rules.')
  L.push('')
  return L.join('\n')
}

describe('the plain-words report', () => {
  it('matches docs/loot-filter-guard.md', async () => {
    await expect(report()).toMatchFileSnapshot('../../../docs/loot-filter-guard.md')
  })
})
